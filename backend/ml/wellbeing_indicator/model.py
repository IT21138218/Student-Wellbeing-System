"""Inference-side loader for the Wellbeing Indicator model.

Loads Member 1's REAL trained artifacts (copied from
`Member 1/Wellbeing_Indicator/Model files/` into ./artifacts/) — a Lasso
regression + MinMaxScaler from their own notebook, trained on their own
`student_wellbeing_dataset.csv`. This does NOT retrain; it serves exactly
what that notebook produced.

CAVEAT (documented, not hidden): the notebook reports R² = 1.0000 on its
held-out test split. That is a near-certain sign of target leakage —
`composite_wellbeing_score` in the dataset was very likely generated BY a
formula over these same features when the dataset was built, so the model
is recovering that formula rather than learning a noisy real-world
relationship. Treat these eval numbers as "the pipeline is wired
correctly," not "this model generalizes to real students." Retraining on
genuinely independent data (not one generated by a known formula) is the
fix — see ml/wellbeing_indicator/train.py for a from-scratch alternative.
"""

from functools import lru_cache
from pathlib import Path

import joblib
import pandas as pd

from ml.wellbeing_indicator.features import RAW_FEATURES, compute_dimensions, engineer_features

ARTIFACT_DIR = Path(__file__).parent / "artifacts"
MODEL_PATH = ARTIFACT_DIR / "real_model.pkl"
SCALER_PATH = ARTIFACT_DIR / "real_scaler.pkl"

# As reported by Member 1's notebook (Section 6, "Best Model: Lasso").
# See the leakage caveat above before quoting these as real-world accuracy.
REPORTED_EVAL_METRICS = {
    "mae": 0.0256,
    "rmse": 0.0301,
    "r_squared": 1.0000,
    "mape": 0.04,
}


class WellbeingModelNotTrained(RuntimeError):
    pass


@lru_cache
def _load_artifact() -> dict:
    if not MODEL_PATH.exists() or not SCALER_PATH.exists():
        raise WellbeingModelNotTrained(
            f"Missing {MODEL_PATH.name}/{SCALER_PATH.name} in {ARTIFACT_DIR}. "
            "Copy them from 'Member 1/Wellbeing_Indicator/Model files/'."
        )
    return {"model": joblib.load(MODEL_PATH), "scaler": joblib.load(SCALER_PATH)}


def predict_score(features: dict) -> float:
    """Just the composite score, no narrative/dimensions — used internally
    by ml/risk_classification, whose real model takes this score as one of
    its own inputs (a chained, two-stage pipeline: Wellbeing -> Risk)."""
    artifact = _load_artifact()
    df = pd.DataFrame([{k: features[k] for k in RAW_FEATURES}])
    X = engineer_features(df)
    X_scaled = pd.DataFrame(artifact["scaler"].transform(X), columns=X.columns)
    score = float(artifact["model"].predict(X_scaled)[0])
    return max(0.0, min(100.0, score))


def predict(features: dict) -> dict:
    artifact = _load_artifact()
    score = predict_score(features)
    # Lasso has no risk_label of its own. ml/risk_classification now has the
    # REAL trained classifier (chained: this score is one of its inputs) —
    # this bucket is only a rough fallback for the standalone Wellbeing
    # endpoint's own display, not what Risk Classification actually uses.
    risk_label = "LOW" if score >= 70 else "MEDIUM" if score >= 50 else "HIGH"

    df = pd.DataFrame([{k: features[k] for k in RAW_FEATURES}])
    X = engineer_features(df)
    coefs = getattr(artifact["model"], "coef_", None)
    top_features_out = []
    if coefs is not None:
        # Raw Lasso coefficients are in score points per scaled unit (e.g. 24.6),
        # not a 0-1 share, so express each as its fraction of total |coef|.
        total = sum(abs(float(c)) for c in coefs) or 1.0
        pairs = sorted(zip(X.columns, coefs), key=lambda kv: abs(kv[1]), reverse=True)[:5]
        top_features_out = [
            {"feature": name, "importance": round(abs(float(c)) / total, 4), "direction": "positive" if c > 0 else "negative"}
            for name, c in pairs
        ]

    return {
        "composite_wellbeing_score": round(score, 1),
        "risk_label": risk_label,
        "dimensions": compute_dimensions(features),
        "eval_metrics": REPORTED_EVAL_METRICS,
        "top_features": top_features_out,
    }
